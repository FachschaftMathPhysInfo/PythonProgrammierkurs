# Spielwiese fuers REPL.
#
# WICHTIG: Kopiere dir eine Zeile nach der anderen ins REPL -- nicht die
# ganze Datei auf einmal! Nach jeder Zeile: kurz nachdenken, was wohl
# passiert, DANN Enter druecken und mit der Vorhersage vergleichen.

# 1. Eine Variable anlegen
alter = 19

# 2. Variable direkt eingeben -- was zeigt das REPL dir an?
alter

# 3. Mit der Variable rechnen
alter + 1

# 4. Ergebnis in einer neuen Variable speichern und anzeigen lassen
alter_naechstes_jahr = alter + 1
alter_naechstes_jahr

# 5. Der Unterstrich _ merkt sich automatisch das letzte Ergebnis
alter_naechstes_jahr * 2
_

# 6. Funktioniert genauso mit Text (Strings)
name = "Ada"
"Hallo " + name

# 7. Python kennt noch mehr Rechenzeichen als +, -, *, /.
#    Ueberlege dir VOR dem Eintippen, was wohl herauskommt!
2 ** 10
7 // 2
7 % 2
